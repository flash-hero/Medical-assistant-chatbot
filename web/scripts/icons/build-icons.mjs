function attr(name, value) {
  if (typeof value === "number") return `${name}={${value}}`;
  if (typeof value !== "string") throw new TypeError(`unsupported SVG attribute ${name}`);
  return `${name}=${JSON.stringify(value)}`;
}

/** Serialise one React element tree (a Fragment of SVG shapes) to JSX source. */
function toJsx(element) {
  if (element === null || element === undefined || element === false) return "";
  if (Array.isArray(element)) return element.map(toJsx).join("");
  const { children, ...props } = element.props ?? {};
  if (typeof element.type !== "string") return toJsx(children);
  const attrs = Object.entries(props).map(([k, v]) => attr(k, v));
  const inner = toJsx(children);
  const open = [element.type, ...attrs].join(" ");
  return inner ? `<${open}>${inner}</${element.type}>` : `<${open} />`;
}

async function iconSource(name, weights) {
  const defs = (await import(pathToFileURL(`${PKG_DIR}dist/defs/${name}.es.js`).href)).default;
  const body = (weight) => {
    const tree = defs.get(weight);
    if (!tree) throw new Error(`${name} has no "${weight}" weight`);
    return toJsx(tree);
  };
  const union = weights.map((w) => JSON.stringify(w)).join(" | ");
  const [fallback, ...others] = weights;
  const chosen = others.reduceRight((rest, w) => `weight === ${JSON.stringify(w)} ? <>${body(w)}</> : ${rest}`, `<>${body(fallback)}</>`);
  return [
    `export function ${name}Icon({ weight = ${JSON.stringify(fallback)}, ...props }: IconProps & { readonly weight?: ${union} }) {`,
    `  return <Icon {...props}>{${others.length ? chosen : `weight === ${JSON.stringify(fallback)} ? <>${body(fallback)}</> : null`}}</Icon>;`,
    "}",
  ].join("\n");
}

const version = JSON.parse(readFileSync(require.resolve("@phosphor-icons/react/package.json"), "utf8")).version;
const header = `/**
 * GENERATED by scripts/icons/build-icons.mjs (npm run icons). Do not edit.
 * Icon paths: Phosphor Icons ${version}, MIT License, Copyright (c) 2020 Phosphor Icons.
 * Only the weights the site renders are included (see ICONS in the script).
 */
import type { ReactNode, SVGProps } from "react";

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "children"> {
  readonly size?: number | string;
}

function Icon({ size = "1em", children, ...rest }: IconProps & { readonly children: ReactNode }) {
  return (
    <svg xmlns="http://www.w3.org/2000/svg" width={size} height={size} fill="currentColor" viewBox="0 0 256 256" {...rest}>
      {children}
    </svg>
  );
}
`;

const parts = [];
for (const [name, weights] of Object.entries(ICONS)) parts.push(await iconSource(name, weights));
const temp = `${OUT}.${process.pid}.tmp`;
writeFileSync(temp, `${header}\n${parts.join("\n\n")}\n`, "utf8");
renameSync(temp, OUT);
console.log(`wrote ${parts.length} icons to ${OUT}`);
