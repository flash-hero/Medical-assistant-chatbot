#!/usr/bin/env node
/**
 * Generates src/components/ui/icons.tsx: the Phosphor icons the site uses, with only the weights
 * it renders. Phosphor's own components ship all six weights of every icon to the browser (about
 * 3 kB raw each); this keeps one or two. Paths come verbatim from @phosphor-icons/react (MIT).
 * Add an icon: list it in ICONS, then run  npm run icons
 */
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

